"""Build the local barcode catalog from an Open Food Facts Israel TSV export."""

import argparse
import csv
import json
import math
import re
from pathlib import Path


def valid_gtin(code):
    if not re.fullmatch(r"[0-9]{8}|[0-9]{12,14}", code):
        return False
    return sum(int(digit) * (1 if i % 2 == 0 else 3)
               for i, digit in enumerate(reversed(code))) % 10 == 0


def declared_energy(row):
    for source in ("packaging", "manufacturer"):
        for basis, unit in (("100g", "g"), ("100ml", "ml")):
            prefix = f"nutrition.input_sets.{source}.as_sold.{basis}."
            if row.get(prefix + "per_unit") != unit:
                continue
            for field, factor in (("energy-kcal", 1), ("energy-kj", 4.184)):
                raw = row.get(prefix + f"nutrients.{field}.value", "")
                if raw:
                    try:
                        kcal = float(raw) / factor
                    except ValueError:
                        continue
                    if math.isfinite(kcal) and 0 <= kcal <= 900:
                        return round(kcal, 2), unit
    return None


def catalog_row(row):
    code = row["code"].strip()
    if (not valid_gtin(code) or row.get("obsolete") == "1"
            or "en:israel" not in row.get("countries_tags", "").split(",")):
        return None
    suffixes = dict.fromkeys(["he", "iw", row.get("lc"), "en", "fr", "ru", "ar"])
    names = [row.get(f"product_name_{lang}", "").strip() for lang in suffixes if lang]
    names = [name for name in dict.fromkeys(names) if name and not name.isdigit()]
    energy = declared_energy(row)
    if not names or energy is None:
        return None
    kcal, unit = energy
    result = [code, names[0], kcal, unit, row.get("brands", "").strip(), " ".join(names[1:])]
    pack = re.fullmatch(r"(\d+(?:[.,]\d+)?)\s*(g|ml|גרם|מ[\"״']ל)", row.get("quantity", "").strip(), re.I)
    if pack:
        size = float(pack[1].replace(",", "."))
        pack_unit = "g" if pack[2].lower() in ("g", "גרם") else "ml"
        if 0 < size <= 3000 and pack_unit == unit:
            result.append(int(size) if size.is_integer() else size)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("export_tsv", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with args.export_tsv.open(encoding="utf-8-sig", newline="") as source:
        products = {}
        for row in csv.DictReader(source, delimiter="\t"):
            product = catalog_row(row)
            if product:
                products[product[0]] = product
    if not products:
        parser.error("No usable products found. Verify the source export.")
    lines = [json.dumps(products[code], ensure_ascii=False, separators=(",", ":"))
             for code in sorted(products)]
    args.output.write_text(
        "// Open Food Facts contributors, ODbL 1.0. Generated by scripts/import-israeli-products.py.\n"
        "export default [\n" + ",\n".join(lines) + "\n]\n",
        encoding="utf-8",
    )
    print(f"Imported {len(products):,} products")


if __name__ == "__main__":
    main()
